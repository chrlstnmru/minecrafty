import { describe, expect, it } from 'vitest';

import { isHtmlComment, parseMarkdown, safeHref } from './markdown';

describe('parseMarkdown', () => {
	it('reads headings, bullet lists and links the way GitHub writes release notes', () => {
		const [heading, list] = parseMarkdown(
			"## What's Changed\n* fix: keep the sidebar open by @a in https://github.com/o/r/pull/1\n"
		);
		expect(heading).toMatchObject({ type: 'heading', depth: 2, text: "What's Changed" });
		expect(list).toMatchObject({ type: 'list', ordered: false });
		const item = (list as { items: { tokens: { tokens: { type: string; href?: string }[] }[] }[] })
			.items[0];
		expect(item.tokens[0].tokens.at(-1)).toMatchObject({
			type: 'link',
			href: 'https://github.com/o/r/pull/1'
		});
	});

	it('keeps raw HTML as an html token instead of passing it through', () => {
		const [html] = parseMarkdown('<script>alert(1)</script>');
		expect(html).toMatchObject({ type: 'html' });
	});
});

describe('safeHref', () => {
	it('allows http and https links', () => {
		expect(safeHref('https://github.com/o/r')).toBe('https://github.com/o/r');
		expect(safeHref('HTTP://example.com')).toBe('HTTP://example.com');
	});

	it('refuses anything that could run code or leave the web', () => {
		expect(safeHref('javascript:alert(1)')).toBeNull();
		expect(safeHref(' javascript:alert(1)')).toBeNull();
		expect(safeHref('data:text/html,<b>x</b>')).toBeNull();
		expect(safeHref('//example.com')).toBeNull();
		expect(safeHref('#section')).toBeNull();
	});
});

describe('isHtmlComment', () => {
	it('spots a comment, but not other HTML', () => {
		expect(isHtmlComment('<!-- generated by the release workflow -->')).toBe(true);
		expect(isHtmlComment('  <!-- indented -->')).toBe(true);
		expect(isHtmlComment('<details>')).toBe(false);
	});
});
