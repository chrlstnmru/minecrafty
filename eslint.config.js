import { plugin as shadcn } from '@shadcn/lint';
import prettier from 'eslint-config-prettier';
import oxlint from 'eslint-plugin-oxlint';
import path from 'node:path';
import js from '@eslint/js';
import svelte from 'eslint-plugin-svelte';
import { defineConfig, includeIgnoreFile } from 'eslint/config';
import globals from 'globals';
import ts from 'typescript-eslint';

const gitignorePath = path.resolve(import.meta.dirname, '.gitignore');

export default defineConfig(
	includeIgnoreFile(gitignorePath),
	js.configs.recommended,
	ts.configs.recommended,
	svelte.configs.recommended,
	prettier,
	svelte.configs.prettier,
	{
		languageOptions: { globals: { ...globals.browser, ...globals.node } },
		// oxlint reads the same disable comments, so eslint can't tell when they're still needed
		linterOptions: { reportUnusedDisableDirectives: 'off' },
		rules: {
			// typescript-eslint strongly recommend that you do not use the no-undef lint rule on TypeScript projects.
			// see: https://typescript-eslint.io/troubleshooting/faqs/eslint/#i-get-errors-from-the-no-undef-rule-about-global-variables-not-being-defined-even-though-there-are-no-typescript-errors
			'no-undef': 'off'
		}
	},
	{
		files: ['**/*.svelte', '**/*.svelte.ts', '**/*.svelte.js'],
		plugins: { shadcn },
		rules: {
			// colors come from the theme tokens in src/routes/layout.css (including info, success, warning and danger)
			'shadcn/no-raw-colors': 'error',
			// a class Tailwind cannot generate does nothing: a typo, or one that needs an @utility
			'shadcn/no-unknown-classes': 'error',
			// dynamic values go through CSS custom properties (style="--total: 40px" with h-(--total))
			'shadcn/no-inline-styles': 'error',
			// a class the linter cannot read cannot be checked either, so classes are written out
			'shadcn/require-static-classes': 'error',
			// layout values (grid-cols-[auto_1fr], [column-span:all]) are fine; hardcoded appearance
			// (pixel font sizes, radii, colours, spacing off the scale) is not
			'shadcn/no-arbitrary-values': ['error', { allow: ['layout', 'transition-[width,height]'] }]
		},
		languageOptions: {
			parserOptions: {
				// no type-aware rules are enabled, and building the TS program for every
				// .svelte file is what made eslint take ~45s instead of ~2s
				projectService: false,
				extraFileExtensions: ['.svelte'],
				parser: ts.parser
			}
		}
	},
	{
		// generated by shadcn-svelte and rewritten whenever a component is updated from the CLI, so
		// its structural values stay as they ship
		files: ['src/lib/components/ui/**'],
		rules: {
			'shadcn/no-inline-styles': 'off',
			'shadcn/require-static-classes': 'off',
			'shadcn/no-arbitrary-values': 'off'
		}
	},
	{
		// a column's own classes come from its definition (`meta.class`), so they cannot be static
		files: ['src/lib/components/data-table/**'],
		rules: { 'shadcn/require-static-classes': 'off' }
	},
	{
		// Override or add rule settings here, such as:
		// 'svelte/button-has-type': 'error'
		rules: {
			'svelte/no-navigation-without-resolve': 'off',
			// covered by oxlint (see oxlint.config.ts), which also handles the `_` ignore patterns
			'@typescript-eslint/no-unused-vars': 'off'
		}
	},
	// must stay last: disables the ESLint rules that oxlint already runs
	...(await oxlint.buildFromConfigFile('./oxlint.config.ts'))
);
